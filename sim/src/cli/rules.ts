// `sim rules <package-dir> [--check]`: write `rules.yaml` from the research documents that the
// manifest `researchBase` names, or check that the file on disk is current (11 P4-08; DEC-83).
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { parse, stringify } from "yaml";
import { buildRuleIndex, ruleEntries, type RuleEntry } from "../annotate/rule-index.ts";
import { readPackageDir } from "../package/load.ts";
import { readResearchDocs } from "../package/research.ts";

const HEADER = "# Generated by `sim rules <package-dir>` from the research documents named by manifest.researchBase.\n# Do not edit by hand (11 P4-08; DEC-83).\n";

/**
 * The entries the research documents give for a package. Empty when the base is unset or missing.
 * Reads the raw manifest, not the loaded package, so a stale or invalid rules.yaml can be rewritten.
 */
function generatedRules(packageDir: string): RuleEntry[] | null {
  const manifest = readPackageDir(packageDir).files["manifest.yaml"];
  if (typeof manifest !== "object" || manifest === null) return null;
  const base = (manifest as Record<string, unknown>)["researchBase"];
  return ruleEntries(buildRuleIndex(readResearchDocs(dirname(dirname(resolve(packageDir))), typeof base === "string" ? base : undefined)));
}

export function rulesCommand(packageDir: string, check: boolean): { exitCode: number; lines: string[] } {
  const entries = generatedRules(packageDir);
  if (entries === null) return { exitCode: 1, lines: [`error: the package has no manifest.yaml: ${packageDir}`] };
  if (entries.length === 0) return { exitCode: 1, lines: ["error: no research documents found; check manifest researchBase"] };
  const file = join(packageDir, "rules.yaml");
  if (check) {
    // Parsed, not raw text: a CRLF checkout of the file is still current.
    const current = existsSync(file) ? (parse(readFileSync(file, "utf8")) as unknown) : null;
    return JSON.stringify(current) === JSON.stringify(entries) ? { exitCode: 0, lines: [`rules.yaml is current (${String(entries.length)} sections)`] } : { exitCode: 1, lines: ["rules.yaml is missing or stale. Run: npm run sim -- rules <package-dir>"] };
  }
  writeFileSync(file, `${HEADER}${stringify(entries, { lineWidth: 0 })}`);
  return { exitCode: 0, lines: [`wrote ${file}: ${String(entries.length)} sections`] };
}
